export function getBankNameByCode(code?: string | null): string | null {
  if (!code) return null;
  const normalized = String(code).trim();
  if (!normalized) return null;
  if (LEGACY_BANK_CODES[normalized]) return LEGACY_BANK_CODES[normalized];
  const found = BANK_LIST.find((b) => b.code === normalized);
  return found ? found.name : null;
}
